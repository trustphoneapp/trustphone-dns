import java.util.Properties

val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use(::load)
    }
}

fun signingValue(propertyName: String, environmentName: String): String? =
    keystoreProperties.getProperty(propertyName)?.takeIf { it.isNotBlank() }
        ?: System.getenv(environmentName)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("storeFile", "SHIELD_DNS_STORE_FILE")
val releaseStorePassword = signingValue("storePassword", "SHIELD_DNS_STORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "SHIELD_DNS_KEY_ALIAS")
